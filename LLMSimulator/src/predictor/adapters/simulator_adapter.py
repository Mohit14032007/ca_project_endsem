"""
Simulator Dataset Adapters for DeepSeek-V3 Random and Duplex A100 Traces.
"""

from typing import Any, Dict, Iterator, List, Optional, Set, Tuple
import os
import pandas as pd
import numpy as np

from src.predictor.adapters.base_adapter import (
    PredictionRecord,
    RoutingDatasetAdapter
)
from src.predictor.trace_parser import (
    RoutingTraceParser,
    NormalizedRoutingRecord,
    ModelArchitectureConfig
)


class SimulatorDatasetAdapter(RoutingDatasetAdapter):
    """
    Adapter for traces generated by the LLMSimulator execution engine.
    Supports both DeepSeek-V3 random trace (negative control) and Duplex A100 trace.
    """

    def __init__(
        self,
        dataset_id: str,
        trace_path: str,
        num_moe_stages: int,
        num_routed_experts: int,
        top_k: int,
        first_k_dense: int = 0,
        reconstruct_stages: bool = False,
        train_ratio: float = 0.75
    ):
        super().__init__(dataset_id=dataset_id)
        self.trace_path = trace_path
        self.num_moe_stages = num_moe_stages
        self.num_routed_experts = num_routed_experts
        self.top_k = top_k
        self.first_k_dense = first_k_dense
        self.reconstruct_stages = reconstruct_stages
        self.train_ratio = train_ratio

        self.records: List[NormalizedRoutingRecord] = []
        self.splits: Dict[str, List[Any]] = {"train": [], "test": []}
        self.grouped_routes: Dict[Tuple[Any, int, int], List[int]] = {}

    def load(self) -> None:
        if not os.path.exists(self.trace_path):
            raise FileNotFoundError(f"Trace file not found: {self.trace_path}")

        arch_config = ModelArchitectureConfig(
            num_layers=self.num_moe_stages + self.first_k_dense,
            first_k_dense=self.first_k_dense,
            num_routed_experts=self.num_routed_experts,
            top_k=self.top_k,
            name=self.dataset_id
        )

        parser = RoutingTraceParser(config=arch_config)

        self.records = parser.parse_file(
            self.trace_path,
            reconstruct_stages_from_sequence=self.reconstruct_stages
        )

        # Group records by (request_id, token_id, moe_stage_id)
        self.grouped_routes = {}
        for rec in self.records:
            key = (rec.request_id, rec.token_id, rec.moe_stage_id)
            if key not in self.grouped_routes:
                self.grouped_routes[key] = []
            self.grouped_routes[key].append(rec.expert_id)

        # Compute splits
        unique_requests = sorted(list(set(r.request_id for r in self.records)))
        num_requests = len(unique_requests)

        if num_requests <= 1:
            self.splits["train"] = unique_requests
            self.splits["test"] = unique_requests
        else:
            num_train = max(1, int(round(num_requests * self.train_ratio)))
            self.splits["train"] = unique_requests[:num_train]
            self.splits["test"] = unique_requests[num_train:]

        self.is_loaded = True
        self.metadata = {
            "dataset_id": self.dataset_id,
            "trace_path": self.trace_path,
            "num_moe_stages": self.num_moe_stages,
            "num_routed_experts": self.num_routed_experts,
            "top_k": self.top_k,
            "total_records": len(self.records),
            "num_requests": num_requests,
            "train_requests": len(self.splits["train"]),
            "test_requests": len(self.splits["test"]),
            "reconstruct_stages": self.reconstruct_stages
        }

    def validate(self) -> Dict[str, Any]:
        if not self.is_loaded:
            self.load()

        missing_records = 0
        duplicate_records = 0
        invalid_expert_ids = 0
        inconsistent_topk = 0

        seen_keys: Set[Tuple[Any, int, int, int]] = set()

        for rec in self.records:
            # Check expert bounds
            if rec.expert_id < 0 or rec.expert_id >= self.num_routed_experts:
                invalid_expert_ids += 1

            # Check duplicates
            key = (rec.request_id, rec.token_id, rec.moe_stage_id, rec.expert_id)
            if key in seen_keys:
                duplicate_records += 1
            else:
                seen_keys.add(key)

        # Check Top-K consistency per stage activation
        for key, experts in self.grouped_routes.items():
            if len(experts) != self.top_k:
                inconsistent_topk += 1

        # Check unique tokens and stages
        unique_tokens = sorted(list(set(r.token_id for r in self.records)))
        unique_requests = sorted(list(set(r.request_id for r in self.records)))

        report = {
            "dataset_id": self.dataset_id,
            "total_records": len(self.records),
            "num_requests": len(unique_requests),
            "num_tokens_total": len(unique_tokens),
            "num_moe_stages": self.num_moe_stages,
            "num_routed_experts": self.num_routed_experts,
            "top_k": self.top_k,
            "missing_records": missing_records,
            "duplicate_records": duplicate_records,
            "invalid_expert_ids": invalid_expert_ids,
            "inconsistent_topk_count": inconsistent_topk,
            "train_requests_count": len(self.splits["train"]),
            "test_requests_count": len(self.splits["test"]),
            "is_single_request": len(unique_requests) <= 1
        }
        return report

    def get_splits(self) -> Dict[str, List[Any]]:
        if not self.is_loaded:
            self.load()
        return self.splits

    def iter_predictions(
        self,
        horizon: int = 1,
        split: Optional[str] = None
    ) -> Iterator[PredictionRecord]:
        if not self.is_loaded:
            self.load()

        if split is not None:
            target_requests = set(self.splits.get(split, []))
        else:
            target_requests = set(self.splits.get("train", []) + self.splits.get("test", []))

        # Iterate in causal sequence: request -> token -> stage
        unique_requests = sorted(list(target_requests))
        for req in unique_requests:
            req_keys = [k for k in self.grouped_routes.keys() if k[0] == req]
            req_tokens = sorted(list(set(k[1] for k in req_keys)))

            # Determine split label for this request
            if req in self.splits.get("test", []):
                req_split = "test"
            else:
                req_split = "train"

            for tok in req_tokens:
                for target_stage in range(self.num_moe_stages):
                    source_stage = target_stage - horizon
                    if source_stage < 0:
                        source_experts = []
                    else:
                        source_key = (req, tok, source_stage)
                        source_experts = self.grouped_routes.get(source_key, [])

                    target_key = (req, tok, target_stage)
                    actual_target = self.grouped_routes.get(target_key, [])
                    if len(actual_target) == 0:
                        continue

                    rec = PredictionRecord(
                        dataset_id=self.dataset_id,
                        split=req_split,
                        request_id=req,
                        token_id=tok,
                        source_stage_id=source_stage,
                        target_stage_id=target_stage,
                        source_experts=source_experts,
                        actual_target_experts=actual_target,
                        source_routing_weights=None,
                        target_routing_weights=None,
                        prediction_horizon=horizon
                    )
                    yield rec
